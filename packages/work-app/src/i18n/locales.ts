export const LOCALES: Record<string, Record<LocaleKey, string>> = {
  'zh-CN': zhCN as Record<LocaleKey, string>,
  'en-US': enUS,
};

export const LANG_NAMES: Record<string, string> = {
  'zh-CN': '简体中文',
  'en-US': 'English',
};

export const SUPPORTED_LANGS = ['zh-CN', 'en-US'] as const;
export type SupportedLang = (typeof SUPPORTED_LANGS)[number];
export const DEFAULT_LANG: SupportedLang = 'zh-CN';

/** 把任意输入归一化成受支持的语言；无法识别时回退默认。 */
export function normalizeLang(input: string | null | undefined): SupportedLang {
  if (input && (SUPPORTED_LANGS as readonly string[]).includes(input)) return input as SupportedLang;
  if (input && (input.toLowerCase() === 'zh' || input.toLowerCase().startsWith('zh'))) return 'zh-CN';
  if (input && (input.toLowerCase() === 'en' || input.toLowerCase().startsWith('en'))) return 'en-US';
  return DEFAULT_LANG;
}